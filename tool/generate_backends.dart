/// Writes the generated parts of the Dart backends from src/lua_dart.h:
///
/// - lib/src/backend/constants.g.dart: the LUADART_* constants;
/// - lib/src/backend/api_native.g.dart: the functions of the C ABI over the
///   ffigen bindings, with every pointer as an int address;
/// - lib/src/backend/api_web.g.dart: the same functions over the exports of
///   the Emscripten module.
///
/// Both backends have the same functions, so lib/src/lua_state.dart works
/// with either through a conditional import. Run it after a change to the
/// header, after ffigen. With `--check`, it fails if a file differs.
library;

import 'dart:io';

final _function = RegExp(r'\n([A-Za-z_][\w \*]*?)\b(luadart_\w+)\(([^)]*)\);');
final _define = RegExp(
  r'#define (LUADART_\w+) (\(-\d+\)|-?\d+|\(1u? << \d+\)|0x[0-9a-fA-F]+u?)\s*$',
  multiLine: true,
);

enum _Kind { i32, i64, f64, pointer, none }

_Kind _kindOf(String cType) {
  final t = cType.replaceAll('const ', '').replaceAll(' ', '');
  if (t.endsWith('*') || t == 'luadart_host_fn') return _Kind.pointer;
  return switch (t) {
    'void' => _Kind.none,
    'int32_t' || 'uint32_t' => _Kind.i32,
    'int64_t' || 'uint64_t' => _Kind.i64,
    'double' => _Kind.f64,
    _ => throw FormatException('lua_dart.h: unknown C type $cType'),
  };
}

final class _Param {
  _Param(this.kind, this.name);
  final _Kind kind;
  final String name;
}

final class _Function {
  _Function(this.name, this.result, this.params);
  final String name;
  final _Kind result;
  final List<_Param> params;
}

List<_Function> _functions(String header) {
  final code = header.replaceAll(RegExp(r'//[^\n]*'), '');
  return [
    for (final m in _function.allMatches(code))
      _Function(m[2]!, _kindOf(m[1]!.trim()), [
        for (final p in m[3]!.split(','))
          if (p.trim() != 'void' && p.trim().isNotEmpty)
            () {
              final parts = p.trim().split(RegExp(r'\s+'));
              final name = parts.last.replaceAll('*', '');
              final type = p.trim().substring(0, p.trim().length - name.length);
              return _Param(_kindOf(type), name == 'L' ? 'l' : name);
            }(),
      ]),
  ];
}

String _dartType(_Kind k) => switch (k) {
  _Kind.none => 'void',
  _Kind.f64 => 'double',
  _ => 'int',
};

const _header =
    '// Generated by tool/generate_backends.dart from src/lua_dart.h. '
    'Do not edit.\n';

String _constants(String header) {
  final b = StringBuffer(_header)
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln();
  for (final m in _define.allMatches(header)) {
    final value = m[2]!
        .replaceAll(RegExp(r'(?<=[0-9A-Fa-f])u'), '')
        .replaceAll(RegExp(r'[()]'), '');
    b.writeln('const ${m[1]} = $value;');
  }
  return '$b';
}

String _native(List<_Function> functions) {
  final b = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names')
    ..writeln()
    ..writeln("import 'dart:ffi';")
    ..writeln()
    ..writeln("import '../lua_dart_bindings_generated.dart' as ffi_b;")
    ..writeln();
  for (final f in functions) {
    final params = f.params.map((p) => '${_dartType(p.kind)} ${p.name}');
    final args = f.params.map(
      (p) =>
          p.kind == _Kind.pointer ? 'Pointer.fromAddress(${p.name})' : p.name,
    );
    final call = 'ffi_b.${f.name}(${args.join(', ')})';
    b
      ..writeln("@pragma('vm:prefer-inline')")
      ..writeln(
        '${_dartType(f.result)} ${f.name}(${params.join(', ')}) => '
        '${f.result == _Kind.pointer ? '$call.address' : call};',
      );
  }
  return '$b';
}

String _web(List<_Function> functions) {
  String jsType(_Kind k) => switch (k) {
    _Kind.none => 'void',
    _Kind.i64 => 'JSBigInt',
    _ => 'JSNumber',
  };
  String toJs(_Param p) => switch (p.kind) {
    _Kind.i64 => 'toBigInt(${p.name})',
    _ => '${p.name}.toJS',
  };
  String fromJs(_Kind k, String e) => switch (k) {
    _Kind.none => e,
    _Kind.i64 => 'fromBigInt($e)',
    _Kind.f64 => '$e.toDartDouble',
    _ => '$e.toDartInt',
  };
  final b = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names')
    ..writeln()
    ..writeln("import 'dart:js_interop';")
    ..writeln()
    ..writeln("import 'web_module.dart';")
    ..writeln()
    ..writeln('/// The exports of the C ABI in the Emscripten module.')
    ..writeln(
      'extension type LuaDartExports._(JSObject _) implements JSObject {',
    );
  for (final f in functions) {
    final params = f.params.map((p) => '${jsType(p.kind)} ${p.name}');
    b
      ..writeln("  @JS('_${f.name}')")
      ..writeln(
        '  external ${jsType(f.result)} ${f.name}(${params.join(', ')});',
      );
  }
  b
    ..writeln('}')
    ..writeln();
  for (final f in functions) {
    final params = f.params.map((p) => '${_dartType(p.kind)} ${p.name}');
    final call = 'exports.${f.name}(${f.params.map(toJs).join(', ')})';
    b.writeln(
      '${_dartType(f.result)} ${f.name}(${params.join(', ')}) => '
      '${fromJs(f.result, call)};',
    );
  }
  return '$b';
}

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final header = File('src/lua_dart.h').readAsStringSync();
  final functions = _functions(header);
  final files = {
    'lib/src/backend/constants.g.dart': _constants(header),
    'lib/src/backend/api_native.g.dart': _native(functions),
    'lib/src/backend/api_web.g.dart': _web(functions),
  };
  var stale = false;
  for (final MapEntry(key: path, value: raw) in files.entries) {
    final formatted = await _format(raw);
    final file = File(path);
    if (file.existsSync() && file.readAsStringSync() == formatted) continue;
    if (check) {
      stderr.writeln('$path is stale: run dart tool/generate_backends.dart');
      stale = true;
    } else {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(formatted);
      stdout.writeln('Wrote $path');
    }
  }
  if (stale) exit(1);
  stdout.writeln('${functions.length} functions');
}

Future<String> _format(String source) async {
  final process = await Process.start(Platform.resolvedExecutable, [
    'format',
    '--output=show',
    '--summary=none',
    '--stdin-name=generated.dart',
  ]);
  process.stdin.write(source);
  await process.stdin.close();
  final out = await process.stdout
      .transform(const SystemEncoding().decoder)
      .join();
  if (await process.exitCode != 0) {
    throw StateError('dart format failed');
  }
  return out;
}
